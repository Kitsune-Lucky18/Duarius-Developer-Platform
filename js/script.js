const langNames = { en: "EN", id: "ID", ja: "JA", es: "ES", ko: "KO" };

document.addEventListener('DOMContentLoaded', () => {
    const html = document.documentElement;
    const themeToggle = document.getElementById('themeToggle');
    const themePanel = document.getElementById('themePanel');
    const themeOptions = document.querySelectorAll('.theme-option');
    const langToggle = document.getElementById('langToggle');
    const langDropdown = document.getElementById('langDropdown');
    const langOptions = document.querySelectorAll('.lang-option');
    const secretCodeInput = document.getElementById('secretCode');
    const unlockBtn = document.getElementById('unlockBtn');
    const unlockError = document.getElementById('unlockError');
    const secretUnlockDiv = document.getElementById('secretUnlock');
    const ownerBtn = document.getElementById('ownerBtn');
    const onlyOwnerCard = document.getElementById('onlyOwner');
    const particlesDiv = document.getElementById('particles');
    const faqItems = document.querySelectorAll('.faq-item');
    const statNumbers = document.querySelectorAll('.stat-number');

    const SECRET_CODE = 'KitsuneIsMeCool';
    let currentTheme = localStorage.getItem('theme') || 'kitsune';
    let currentLang = localStorage.getItem('lang') || 'en';
    let isUnlocked = localStorage.getItem('ownerUnlocked') === 'true';
    let countersAnimated = false;

    function setLanguage(lang) {
        currentLang = lang;
        localStorage.setItem('lang', lang);
        const t = translations[lang];
        if (!t) return;
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key]) el.textContent = t[key];
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (t[key]) el.placeholder = t[key];
        });
        langToggle.textContent = '🌐 ' + langNames[lang];
        langOptions.forEach(opt => {
            opt.classList.toggle('active', opt.getAttribute('data-lang') === lang);
        });
    }

    function initTheme() {
        html.setAttribute('data-theme', currentTheme);
        updateActiveTheme();
    }

    function updateActiveTheme() {
        themeOptions.forEach(opt => {
            opt.classList.toggle('active', opt.getAttribute('data-theme') === currentTheme);
        });
    }

    themeToggle.addEventListener('click', () => themePanel.classList.toggle('active'));
    themeOptions.forEach(opt => {
        opt.addEventListener('click', () => {
            currentTheme = opt.getAttribute('data-theme');
            html.setAttribute('data-theme', currentTheme);
            localStorage.setItem('theme', currentTheme);
            updateActiveTheme();
            createParticles();
        });
    });

    langToggle.addEventListener('click', () => langDropdown.classList.toggle('active'));
    langOptions.forEach(opt => {
        opt.addEventListener('click', () => {
            setLanguage(opt.getAttribute('data-lang'));
            langDropdown.classList.remove('active');
        });
    });

    document.addEventListener('click', (e) => {
        if (!langDropdown.contains(e.target) && e.target !== langToggle) langDropdown.classList.remove('active');
        if (!themePanel.contains(e.target) && e.target !== themeToggle) themePanel.classList.remove('active');
    });

    faqItems.forEach(item => {
        item.querySelector('.faq-question').addEventListener('click', () => {
            item.classList.toggle('active');
        });
    });

    function checkSecretCode() {
        const input = secretCodeInput.value.trim();
        if (input === SECRET_CODE) {
            isUnlocked = true;
            localStorage.setItem('ownerUnlocked', 'true');
            unlockOnlyOwner();
            unlockError.textContent = '';
            secretCodeInput.value = '';
        } else {
            const t = translations[currentLang];
            unlockError.textContent = t ? t.error_code : 'Wrong code! Try again...';
            secretCodeInput.value = '';
        }
    }

    function unlockOnlyOwner() {
        onlyOwnerCard.classList.add('unlocked');
        secretUnlockDiv.style.display = 'none';
        ownerBtn.style.display = 'block';
        onlyOwnerCard.querySelector('.popular-badge.hidden').textContent = '🦊 OWNER';
        createConfetti();
    }

    unlockBtn.addEventListener('click', checkSecretCode);
    secretCodeInput.addEventListener('keypress', (e) => { if (e.key === 'Enter') checkSecretCode(); });
    if (isUnlocked) unlockOnlyOwner();

    function animateCounters() {
        if (countersAnimated) return;
        countersAnimated = true;
        statNumbers.forEach(el => {
            const target = parseFloat(el.getAttribute('data-count'));
            const duration = 2000;
            const start = performance.now();
            const isDecimal = target % 1 !== 0;

            function update(now) {
                const elapsed = now - start;
                const progress = Math.min(elapsed / duration, 1);
                const eased = 1 - Math.pow(1 - progress, 3);
                const current = target * eased;

                if (target >= 1000000) {
                    el.textContent = (current / 1000000).toFixed(1) + 'M';
                } else if (target >= 1000) {
                    el.textContent = Math.floor(current).toLocaleString();
                } else if (isDecimal) {
                    el.textContent = current.toFixed(1);
                } else {
                    el.textContent = Math.floor(current);
                }

                if (progress < 1) requestAnimationFrame(update);
            }
            requestAnimationFrame(update);
        });
    }

    const statsObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) animateCounters();
        });
    }, { threshold: 0.3 });
    const statsSection = document.querySelector('.stats');
    if (statsSection) statsObserver.observe(statsSection);

    function createParticles() {
        particlesDiv.innerHTML = '';
        const colors = {
            kitsune: ['#e94560', '#ff8a65', '#ff6b81'],
            minimalist: ['#333', '#666', '#999'],
            midnight: ['#00d4ff', '#7c3aed', '#33ddff'],
            forest: ['#00ff88', '#00cc66', '#33ff99']
        };
        const palette = colors[currentTheme] || colors.kitsune;
        for (let i = 0; i < 25; i++) {
            const p = document.createElement('div');
            p.style.cssText = `position:absolute;width:${Math.random()*4+2}px;height:${Math.random()*4+2}px;background:${palette[Math.floor(Math.random()*palette.length)]};border-radius:50%;left:${Math.random()*100}%;top:${Math.random()*100}%;opacity:${Math.random()*0.3+0.1};animation:float ${Math.random()*6+4}s ease-in-out infinite;animation-delay:${Math.random()*5}s;pointer-events:none;`;
            particlesDiv.appendChild(p);
        }
    }

    function createConfetti() {
        const colors = ['#e94560', '#ff8a65', '#feca57', '#48dbfb', '#ff9ff3'];
        for (let i = 0; i < 50; i++) {
            const c = document.createElement('div');
            c.style.cssText = `position:fixed;width:10px;height:10px;background:${colors[Math.floor(Math.random()*colors.length)]};left:${Math.random()*100}%;top:-10px;border-radius:${Math.random()>0.5?'50%':'0'};z-index:9999;pointer-events:none;`;
            document.body.appendChild(c);
            c.animate([
                { transform: 'translateY(0) rotate(0deg)', opacity: 1 },
                { transform: `translateY(${window.innerHeight}px) rotate(${Math.random()*360}deg)`, opacity: 0 }
            ], { duration: Math.random()*2000+2000, easing: 'cubic-bezier(0,0.9,0.57,1)', delay: Math.random()*500 }).onfinish = () => c.remove();
        }
    }

    document.querySelectorAll('a[href^="#"]').forEach(a => {
        a.addEventListener('click', function(e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) target.scrollIntoView({ behavior: 'smooth', block: 'start' });
        });
    });

    initTheme();
    setLanguage(currentLang);
    createParticles();
});
